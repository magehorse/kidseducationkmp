#!/usr/bin/env python3
"""Regenerates GeneratedDrawables.kt after adding/removing files in composeResources/drawable."""
import os
root=os.path.join(os.path.dirname(__file__),'..','composeApp','src','commonMain')
d=os.path.join(root,'composeResources','drawable')
names=sorted({f.rsplit('.',1)[0] for f in os.listdir(d)})
out=['// GENERATED by tools/gen_drawable_map.py from composeResources/drawable — do not edit by hand.',
'package com.kidsplay.kidseducation.ui','',
'import com.kidsplay.kidseducation.resources.Res',
'import com.kidsplay.kidseducation.resources.*',
'import org.jetbrains.compose.resources.DrawableResource','',
'/** Lets content JSON refer to artwork by name (e.g. "a_apple"). */',
'val drawableByName: Map<String, DrawableResource> = mapOf(']
out+=[f'    "{n}" to Res.drawable.{n},' for n in names if not n[0].isdigit()]
out.append(')')
open(os.path.join(root,'kotlin','com','kidsplay','kidseducation','ui','GeneratedDrawables.kt'),'w').write('\n'.join(out)+'\n')
